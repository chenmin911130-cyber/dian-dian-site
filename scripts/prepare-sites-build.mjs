#!/usr/bin/env node
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildAskShareHtml } from "./lib/inquiry-share-html.mjs";
import { INQUIRY_ASK_SHARE } from "./lib/inquiry-share-meta.mjs";
import { SECURITY_HEADER_VALUES } from "../worker/security-headers.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dist = path.join(root, "dist");
const index = path.join(dist, "client", "index.html");
const workerDir = path.join(root, "worker");
const hosting = path.join(root, ".openai", "hosting.json");

for (const file of [index, path.join(workerDir, "index.js"), hosting]) {
  if (!existsSync(file)) throw new Error("Missing Sites build input: " + file);
}

function extractArticleSlugs(articlesSource) {
  const slugs = [];
  for (const match of articlesSource.matchAll(/"slug":\s*"([^"]+)"/g)) {
    slugs.push(match[1]);
  }
  if (!slugs.length) throw new Error("No article slugs found in src/articles.js");
  return [...new Set(slugs)].sort();
}

const articlesSource = readFileSync(path.join(root, "src", "articles.js"), "utf8");
const slugs = extractArticleSlugs(articlesSource);
const routesData = `// Generated by scripts/prepare-sites-build.mjs — do not edit by hand.
export const STATIC_APP_ROUTES = new Set(["/study", "/career", "/life", "/consult", "/ask"]);
export const ARTICLE_SLUGS = new Set(${JSON.stringify(slugs)});
`;
writeFileSync(path.join(workerDir, "routes-data.js"), routesData);

const shellHtml = readFileSync(index, "utf8");
const askHtml = buildAskShareHtml(shellHtml, INQUIRY_ASK_SHARE);
const askDir = path.join(dist, "client", "ask");
mkdirSync(askDir, { recursive: true });
writeFileSync(path.join(askDir, "index.html"), askHtml);

mkdirSync(path.join(dist, "server"), { recursive: true });
mkdirSync(path.join(dist, ".openai"), { recursive: true });
for (const file of readdirSync(workerDir)) {
  if (!file.endsWith(".js")) continue;
  copyFileSync(path.join(workerDir, file), path.join(dist, "server", file));
}
copyFileSync(hosting, path.join(dist, ".openai", "hosting.json"));

const firebaseHeaders = Object.entries(SECURITY_HEADER_VALUES).map(([key, value]) => ({
  key,
  value,
}));

const firebaseRewrites = [
  "/study",
  "/career",
  "/life",
  "/consult",
  ...slugs.map((slug) => `/article/${slug}`),
].map((source) => ({ source, destination: "/index.html" }));

const firebaseConfig = {
  hosting: {
    site: "diandianyudita",
    public: "dist/client",
    ignore: ["firebase.json", "**/.*", "**/node_modules/**"],
    headers: [{ source: "**", headers: firebaseHeaders }],
    rewrites: firebaseRewrites,
  },
};

writeFileSync(
  path.join(root, "firebase.json"),
  `${JSON.stringify(firebaseConfig, null, 2)}\n`,
);

console.log("Prepared Sites build: dist/server/index.js and dist/.openai/hosting.json");
