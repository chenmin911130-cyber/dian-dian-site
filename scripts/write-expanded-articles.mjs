import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { coreArticles } from "./lib/articles-core.mjs";
import { universityArticles } from "./lib/articles-universities.mjs";
import { highSchoolArticles } from "./lib/articles-highschools.mjs";
import { immigrationArticles } from "./lib/articles-immigration.mjs";

const articles = [
  ...coreArticles(),
  ...universityArticles(),
  ...highSchoolArticles(),
  ...immigrationArticles(),
];

const seen = new Set();
for (const item of articles) {
  if (seen.has(item.slug)) {
    throw new Error(`Duplicate article slug: ${item.slug}`);
  }
  seen.add(item.slug);
}

const outPath = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../src/articles.js",
);

const header = `/** Auto-generated by scripts/write-expanded-articles.mjs — edit scripts/lib/*.mjs, then re-run. */\n\n`;
fs.writeFileSync(outPath, `${header}export const articles = ${JSON.stringify(articles, null, 2)};\n`);

const sitemapPath = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../public/sitemap.xml",
);
const staticPaths = ["/", "/study", "/career", "/life", "/consult"];
const locs = [
  ...staticPaths.map((route) => `https://diandianyudita.com${route === "/" ? "/" : route}`),
  ...articles.map((item) => `https://diandianyudita.com/article/${item.slug}`),
];
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${locs.map((loc) => `  <url><loc>${loc}</loc></url>`).join("\n")}
</urlset>
`;
fs.writeFileSync(sitemapPath, sitemap);

console.log("Wrote", outPath, "articles:", articles.length);
console.log("Wrote", sitemapPath, "urls:", locs.length);
